// M22 MP10b: the internal reference targets content may point at, computed from the repository:
// every file under public/ (as its served path) and every /tools route with a page. Content links
// and images are checked against this list (lib/content/reference-check.ts). The list is committed
// as src/lib/content/reference-targets.ts so the server never reads the filesystem at runtime;
// reference-targets.test.ts fails CI if it drifts. Regenerate with:
//   node scripts/reference-targets.mjs --write
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
export const APP_DIR = path.join(here, "..");
export const TARGETS_MODULE = path.join(
  APP_DIR,
  "src",
  "lib",
  "content",
  "reference-targets.ts",
);

function files(dir, base = dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...files(full, base));
    else if (entry.isFile())
      out.push("/" + path.relative(base, full).split(path.sep).join("/"));
  }
  return out;
}

/** Sorted served paths of public assets and the /tools routes that have a page. */
export function computeReferenceTargets(appDir = APP_DIR) {
  const assets = files(path.join(appDir, "public")).sort();
  const toolsDir = path.join(appDir, "src", "app", "tools");
  const tools = ["/tools"];
  for (const entry of fs.readdirSync(toolsDir, { withFileTypes: true }))
    if (
      entry.isDirectory() &&
      fs.existsSync(path.join(toolsDir, entry.name, "page.tsx"))
    )
      tools.push("/tools/" + entry.name);
  return { assets, tools: tools.sort() };
}

export function renderTargetsModule(targets) {
  const list = (values) =>
    values.map((v) => `    ${JSON.stringify(v)},`).join("\n");
  return `// Generated by scripts/reference-targets.mjs. Do not edit; run it with --write after adding a
// public asset or a /tools page. reference-targets.test.mjs checks this list against the repository.
export const referenceTargets = {
  assets: [
${list(targets.assets)}
  ],
  tools: [
${list(targets.tools)}
  ],
} as const;
`;
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const text = renderTargetsModule(computeReferenceTargets());
  if (process.argv.includes("--write")) {
    fs.writeFileSync(TARGETS_MODULE, text);
    console.log("Reference targets written.");
  } else {
    const current = fs.existsSync(TARGETS_MODULE)
      ? fs.readFileSync(TARGETS_MODULE, "utf8")
      : "";
    if (current !== text) {
      console.error("Reference targets are out of date; run with --write.");
      process.exitCode = 1;
    } else console.log("Reference targets are current.");
  }
}
