import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { assessmentRegistry } from "../assessment-registry";

// The production build scan (scripts/verify-public-bundles.mjs) cannot import TypeScript,
// so it reads these markers. This test keeps them identical to the private quiz data.
// Regenerate after changing quizzes: M22_WRITE_CONTENT_MARKERS=1 pnpm test.
const file = resolve(
  __dirname,
  "../../../scripts/m22-private-content-markers.json",
);

// The longest leading run of characters that HTML and RSC payloads never escape.
function marker(text: string) {
  const run = /^[A-Za-z0-9 ,.;:()-]+/.exec(text)?.[0].trimEnd() ?? "";
  return run.length >= 24 ? run.slice(0, 60).trimEnd() : undefined;
}

function expected() {
  const explanations = [
    ...new Set(
      assessmentRegistry.flatMap((quiz) =>
        quiz.questions.flatMap(
          (question) => marker(question.explanation) ?? [],
        ),
      ),
    ),
  ].sort();
  return {
    note: "Generated by src/lib/content/private-markers.test.ts. Quiz explanations must never reach a browser chunk or an initial HTML/RSC payload.",
    explanationMarkers: explanations,
  };
}

describe("M22 MP04b private content markers", () => {
  it("match every quiz explanation in code", () => {
    const want = expected();
    if (process.env.M22_WRITE_CONTENT_MARKERS === "1")
      writeFileSync(file, JSON.stringify(want, null, 2) + "\n");
    const have = JSON.parse(readFileSync(file, "utf8"));
    expect(have).toEqual(want);
    // Nearly every explanation yields a usable marker; a sudden drop means the rule broke.
    expect(want.explanationMarkers.length).toBeGreaterThan(250);
  });
});
