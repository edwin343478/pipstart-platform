import type { SupabaseClient } from "@supabase/supabase-js";
import { afterEach, describe, expect, it, vi } from "vitest";
import {
  enrollStaffFactor,
  readStaffFactors,
  verifyStaffFactor,
} from "./staff-mfa-flow";
const actor = "2d734acd-a974-45f1-aabc-bc9b0a37fb40";
const factor = "d81ca71d-b4ba-4ef2-83df-0417222bfe5c";
const secret = "JBSWY3DPEHPK3PXP";
const svg =
  'data:image/svg+xml;utf-8,<svg xmlns="http://www.w3.org/2000/svg"></svg>';
function fixture(status = "verified") {
  const row = {
    id: factor,
    status,
    factor_type: "totp",
    friendly_name: "Device",
  };
  const getUser = vi
    .fn()
    .mockResolvedValue({ data: { user: { id: actor } }, error: null });
  const listFactors = vi.fn().mockResolvedValue({
    data: { all: [row], totp: status === "verified" ? [row] : [] },
    error: null,
  });
  const enroll = vi.fn().mockResolvedValue({
    data: { id: factor, totp: { qr_code: svg, secret } },
    error: null,
  });
  const challenge = vi
    .fn()
    .mockResolvedValue({ data: { id: "challenge-id" }, error: null });
  const verify = vi
    .fn()
    .mockResolvedValue({ data: { user: { id: actor } }, error: null });
  const client = {
    auth: { getUser, mfa: { listFactors, enroll, challenge, verify } },
  } as unknown as SupabaseClient;
  return { client, getUser, listFactors, enroll, challenge, verify };
}
afterEach(() => vi.useRealTimers());
describe("TOTP provider boundary", () => {
  it("reads only verified TOTP names/IDs and does not create factors on load", async () => {
    const f = fixture();
    expect(await readStaffFactors(f.client, actor)).toEqual({
      kind: "ready",
      canEnroll: true,
      factors: [{ id: factor, name: "Device" }],
    });
    expect(f.enroll).not.toHaveBeenCalled();
  });
  it("detects an incomplete enrollment instead of creating more factors", async () => {
    const f = fixture("unverified");
    expect(await readStaffFactors(f.client, actor)).toEqual({
      kind: "ready",
      canEnroll: false,
      factors: [],
    });
    expect(await enrollStaffFactor(f.client, actor)).toEqual({
      kind: "changed",
    });
    expect(f.enroll).not.toHaveBeenCalled();
  });
  it("rechecks identity before enrollment or verification", async () => {
    const f = fixture();
    f.getUser.mockResolvedValue({
      data: { user: { id: factor } },
      error: null,
    });
    expect(await enrollStaffFactor(f.client, actor)).toEqual({
      kind: "changed",
    });
    expect(await verifyStaffFactor(f.client, actor, factor, "123456")).toEqual({
      kind: "changed",
    });
    expect(f.enroll).not.toHaveBeenCalled();
    expect(f.challenge).not.toHaveBeenCalled();
  });
  it("creates exactly one TOTP factor and returns its local image/key without a role", async () => {
    const f = fixture();
    const result = await enrollStaffFactor(f.client, actor);
    expect(result.kind).toBe("setup");
    expect(f.enroll).toHaveBeenCalledTimes(1);
    expect(f.enroll.mock.calls[0][0]).toMatchObject({
      factorType: "totp",
      issuer: "PipStart",
    });
    expect(result).not.toHaveProperty("roles");
  });
  it("returns setup once for the provider's larger SVG representation", async () => {
    const f = fixture();
    const qr =
      'data:image/svg+xml;utf-8,<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg xmlns="http://www.w3.org/2000/svg"><!--' +
      "x".repeat(362_632) +
      "--></svg>";
    f.enroll.mockResolvedValue({
      data: { id: factor, totp: { qr_code: qr, secret } },
      error: null,
    });
    const result = await enrollStaffFactor(f.client, actor);
    expect(result.kind).toBe("setup");
    expect(f.enroll).toHaveBeenCalledTimes(1);
  });
  it("reports an enrollment transport failure as unknown without retrying", async () => {
    const f = fixture();
    f.enroll.mockResolvedValue({ data: null, error: { message: secret } });
    expect(await enrollStaffFactor(f.client, actor)).toEqual({
      kind: "unknown",
    });
    expect(f.enroll).toHaveBeenCalledTimes(1);
  });
  it("does not display foreign image URLs or malformed secrets", async () => {
    const f = fixture();
    f.enroll.mockResolvedValue({
      data: {
        id: factor,
        totp: { qr_code: "https://attacker.test/qr", secret },
      },
      error: null,
    });
    expect(await enrollStaffFactor(f.client, actor)).toEqual({
      kind: "unknown",
    });
  });
  it("validates code and factor before making any provider call", async () => {
    const f = fixture();
    expect(await verifyStaffFactor(f.client, actor, factor, "123")).toEqual({
      kind: "invalid",
    });
    expect(await verifyStaffFactor(f.client, actor, "bad", "123456")).toEqual({
      kind: "invalid",
    });
    expect(f.getUser).not.toHaveBeenCalled();
  });
  it("rejects another or removed factor without challenging", async () => {
    const f = fixture();
    expect(await verifyStaffFactor(f.client, actor, actor, "123456")).toEqual({
      kind: "changed",
    });
    expect(f.challenge).not.toHaveBeenCalled();
  });
  it("cannot verify an unverified factor unless created by this page's setup", async () => {
    const f = fixture("unverified");
    expect(await verifyStaffFactor(f.client, actor, factor, "123456")).toEqual({
      kind: "changed",
    });
    expect(f.challenge).not.toHaveBeenCalled();
    expect(
      await verifyStaffFactor(f.client, actor, factor, "123456", factor),
    ).toEqual({ kind: "verified" });
  });
  it("uses the provider challenge ID and submits a code exactly once", async () => {
    const f = fixture();
    expect(await verifyStaffFactor(f.client, actor, factor, "012345")).toEqual({
      kind: "verified",
    });
    expect(f.challenge).toHaveBeenCalledWith({ factorId: factor });
    expect(f.verify).toHaveBeenCalledExactlyOnceWith({
      factorId: factor,
      challengeId: "challenge-id",
      code: "012345",
    });
  });
  it("never verifies when challenge creation fails", async () => {
    const f = fixture();
    f.challenge.mockResolvedValue({
      data: null,
      error: { message: "backend" },
    });
    expect(await verifyStaffFactor(f.client, actor, factor, "123456")).toEqual({
      kind: "unavailable",
    });
    expect(f.verify).not.toHaveBeenCalled();
  });
  it.each(["mfa_verification_failed", "otp_expired"])(
    "allows a fresh-code attempt after known rejection %s",
    async (code) => {
      const f = fixture();
      f.verify.mockResolvedValue({
        data: null,
        error: { code, message: secret },
      });
      expect(
        await verifyStaffFactor(f.client, actor, factor, "123456"),
      ).toEqual({ kind: "rejected" });
      expect(f.verify).toHaveBeenCalledTimes(1);
    },
  );
  it("redacts unknown provider failures and never automatically retries verification", async () => {
    const f = fixture();
    f.verify.mockResolvedValue({ data: null, error: { message: secret } });
    expect(await verifyStaffFactor(f.client, actor, factor, "123456")).toEqual({
      kind: "unknown",
    });
    expect(f.verify).toHaveBeenCalledTimes(1);
  });
  it("does not call a foreign verification result success", async () => {
    const f = fixture();
    f.verify.mockResolvedValue({ data: { user: { id: factor } }, error: null });
    expect(await verifyStaffFactor(f.client, actor, factor, "123456")).toEqual({
      kind: "unknown",
    });
  });
  it("times out enrollment as unknown and does not repeat the side effect", async () => {
    vi.useFakeTimers();
    const f = fixture();
    f.enroll.mockReturnValue(new Promise(() => {}));
    const result = enrollStaffFactor(f.client, actor);
    await vi.advanceTimersByTimeAsync(8000);
    expect(await result).toEqual({ kind: "unknown" });
    expect(f.enroll).toHaveBeenCalledTimes(1);
  });
});
