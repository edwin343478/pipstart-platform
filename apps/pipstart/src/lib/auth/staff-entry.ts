// UI guidance only. The database remains the authority for every staff read/write.
export const STAFF_REQUEST_DEADLINE_MS = 8_000;
// The real provider generated a 362,632-character SVG during local acceptance.
// Keep input bounded while allowing its verbose QR representation.
export const STAFF_TOTP_QR_MAX_CHARACTERS = 1_048_576;
export const STAFF_ENTRY_PATH = "/admin/access";
export const STAFF_HOME_PATH = "/admin/staff";

export function isTotpCode(value: string) {
  return /^[0-9]{6}$/.test(value);
}

export function isFactorId(value: unknown): value is string {
  return (
    typeof value === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(
      value,
    )
  );
}

export function needsStaffChallenge(current: unknown, next: unknown) {
  return current !== "aal2" || next !== "aal2";
}

// Supabase generates this SVG data URI. Never inject provider markup as HTML or
// send the factor secret to a remote QR/image service.
export function safeTotpQr(value: unknown): string | null {
  if (
    typeof value !== "string" ||
    value.length > STAFF_TOTP_QR_MAX_CHARACTERS ||
    !value.startsWith("data:image/svg+xml;utf-8,")
  )
    return null;
  const svg = value
    .slice("data:image/svg+xml;utf-8,".length)
    .replace(/^\s*<\?xml\s+version=["']1\.0["']\s*\?>\s*/, "")
    .replace(/^<!-- Generated by SVGo -->\s*/, "");
  if (!/^<svg\s/.test(svg) || !svg.trimEnd().endsWith("</svg>")) return null;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

export async function staffDeadline<T>(work: PromiseLike<T>): Promise<T> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    return await Promise.race([
      Promise.resolve(work),
      new Promise<never>((_, reject) => {
        timer = setTimeout(
          () => reject(new Error("Staff request timed out")),
          STAFF_REQUEST_DEADLINE_MS,
        );
      }),
    ]);
  } finally {
    clearTimeout(timer);
  }
}
